//! LSP completions let the editor confirm an abbreviation without inserting
//! indentation. Ordinary typing still uses `workspace/applyEdit`.

use super::Table;
use crate::document::{Document, column_offset, utf16_len};
use crate::lsp::{self, Position};
use serde_json::{Value, json};

const MARKER: &str = "leanInfoviewProxyAbbreviation";

/// Advertise the additional trigger without changing Lean's other capabilities.
pub fn announce(response: &mut Value) {
    let Some(capabilities) = response
        .pointer_mut("/result/capabilities")
        .and_then(Value::as_object_mut)
    else {
        return;
    };
    let provider = capabilities
        .entry("completionProvider")
        .or_insert_with(|| json!({}));
    if !provider.is_object() {
        *provider = json!({});
    }
    let triggers = provider
        .as_object_mut()
        .unwrap()
        .entry("triggerCharacters")
        .or_insert_with(|| json!([]));
    if let Some(triggers) = triggers.as_array_mut()
        && !triggers.iter().any(|trigger| trigger == "\\")
    {
        triggers.push(json!("\\"));
    }
}

/// Return one best match, using a snippet for internal cursor placement if supported.
/// An incomplete list makes the editor re-query after further typing.
pub fn at(table: &Table, doc: &Document, position: Position, snippets: bool) -> Option<Value> {
    let line = doc.line(position.line);
    let end = column_offset(line, position.character);
    if utf16_len(&line[..end]) != position.character {
        return None;
    }
    let backslash = line[..end].rfind('\\')?;
    if !doc.allows_abbreviation(position.line, backslash) {
        return None;
    }
    let prefix = &line[backslash + 1..end];
    let (abbr, symbol) = table.shortest_completion(prefix)?;
    // Do not duplicate an existing suffix when the cursor is inside a shortcut.
    if let Some(next) = line[end..].chars().next()
        && table.is_prefix(&format!("{prefix}{next}"))
    {
        return None;
    }
    let start = Position {
        line: position.line,
        character: utf16_len(&line[..backslash]),
    };
    let snippet = snippets.then_some(symbol.snippet.as_deref()).flatten();
    Some(json!({
        "isIncomplete": true,
        "items": [{
            "label": format!("\\{abbr}"),
            "kind": 12,
            "detail": format!("Lean Unicode: {}", symbol.text),
            "filterText": format!("\\{abbr}"),
            "preselect": true,
            "insertTextFormat": if snippet.is_some() { 2 } else { 1 },
            "textEdit": {"range": lsp::range(start, position), "newText": snippet.unwrap_or(&symbol.text)},
            "data": {MARKER: true},
        }],
    }))
}

/// Lean must never try to resolve completion items generated by the proxy.
pub fn is_ours(item: &Value) -> bool {
    item.get("data")
        .and_then(|data| data.get(MARKER))
        .and_then(Value::as_bool)
        == Some(true)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn complete(text: &str) -> Option<Value> {
        let position = Position {
            line: 0,
            character: utf16_len(text),
        };
        at(
            &Table::load(),
            &Document::new(text.to_owned(), 1),
            position,
            true,
        )
    }

    #[test]
    fn completes_prefixes_and_exact_matches_without_spaces() {
        let result = complete("𝔸 \\alp").unwrap();
        let item = &result["items"][0];
        assert_eq!(item["label"], "\\alpha");
        assert_eq!(item["textEdit"]["newText"], "α");
        assert_eq!(
            item["textEdit"]["range"],
            lsp::range(
                Position {
                    line: 0,
                    character: 3
                },
                Position {
                    line: 0,
                    character: 7
                },
            )
        );
        assert_eq!(result["isIncomplete"], true);
        assert!(is_ours(item));
        assert_eq!(
            complete("\\R").unwrap()["items"][0]["textEdit"]["newText"],
            "ℝ"
        );
        assert_eq!(
            complete("\\r").unwrap()["items"][0]["textEdit"]["newText"],
            "→"
        );
    }

    #[test]
    fn leaves_normal_code_literals_and_abandoned_shortcuts_to_lean() {
        for text in ["def foo", "\\", "\\unknown", "\\alp ", "def s := \"\\alp"] {
            assert!(complete(text).is_none(), "{text}");
        }
        assert!(
            at(
                &Table::load(),
                &Document::new("\\alpha".into(), 1),
                Position {
                    line: 0,
                    character: 4
                },
                true,
            )
            .is_none()
        );
    }

    #[test]
    fn paired_completions_put_the_cursor_inside_only_when_supported() {
        let table = Table::load();
        for (prefix, text, snippet) in [
            ("<>", "⟨⟩", "⟨${0}⟩"),
            ("[[]]", "⟦⟧", "⟦${0}⟧"),
            ("f<<>", "«»", "«${0}»"),
            ("nor", "‖‖", "‖${0}‖"),
        ] {
            let source = format!("\\{prefix}");
            let position = Position {
                line: 0,
                character: utf16_len(&source),
            };
            let doc = Document::new(source, 1);
            for supported in [true, false] {
                let result = at(&table, &doc, position, supported).unwrap();
                let item = &result["items"][0];
                assert_eq!(item["insertTextFormat"], if supported { 2 } else { 1 });
                assert_eq!(
                    item["textEdit"]["newText"],
                    if supported { snippet } else { text }
                );
                assert_eq!(item["detail"], format!("Lean Unicode: {text}"));
            }
        }
    }

    #[test]
    fn preserves_capabilities_and_does_not_duplicate_the_trigger() {
        let mut response = json!({"result": {"capabilities": {
            "hoverProvider": true,
            "completionProvider": {"resolveProvider": true, "triggerCharacters": ["."]},
        }}});
        announce(&mut response);
        announce(&mut response);
        assert_eq!(response["result"]["capabilities"]["hoverProvider"], true);
        assert_eq!(
            response["result"]["capabilities"]["completionProvider"],
            json!({
                "resolveProvider": true, "triggerCharacters": [".", "\\"],
            })
        );
        let mut failed = json!({"error": {"code": -32603}});
        announce(&mut failed);
        assert!(failed.get("result").is_none());
    }
}
